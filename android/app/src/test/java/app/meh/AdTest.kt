package app.meh

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.nio.ByteBuffer

/** Pre-roll ads must never stand in for the real video. */
class AdTest {

    // ---- length readers, on hand-built file headers

    private fun mp4(timescale: Int, duration: Int, version: Int = 0): ByteArray {
        val bb = ByteBuffer.allocate(200)
        bb.putInt(24).put("ftyp".toByteArray()).put("isom".toByteArray()).putInt(0).put("isommp41".toByteArray())
        bb.putInt(120).put("moov".toByteArray())
        bb.putInt(108).put("mvhd".toByteArray()).put(version.toByte()).put(byteArrayOf(0, 0, 0))
        if (version == 0) bb.putInt(0).putInt(0).putInt(timescale).putInt(duration)
        else bb.putLong(0).putLong(0).putInt(timescale).putLong(duration.toLong())
        return bb.array()
    }

    @Test fun readsMp4Length() {
        assertEquals(25.0, MediaProbe.mp4Duration(mp4(1000, 25_000))!!, 0.001)
        assertEquals(200.0, MediaProbe.mp4Duration(mp4(90_000, 18_000_000))!!, 0.001)
        assertEquals(60.0, MediaProbe.mp4Duration(mp4(600, 36_000, version = 1))!!, 0.001)
        assertNull("no header near the start → unknown", MediaProbe.mp4Duration(ByteArray(5000) { 7 }))
    }

    @Test fun readsWebmLength() {
        // EBML magic, TimecodeScale 1 ms (0x0F4240), Duration 60008.0 (double)
        val bb = ByteBuffer.allocate(64)
        bb.put(byteArrayOf(0x1a, 0x45, 0xdf.toByte(), 0xa3.toByte(), 0x9f.toByte()))
        bb.put(byteArrayOf(0x2a, 0xd7.toByte(), 0xb1.toByte(), 0x83.toByte(), 0x0f, 0x42, 0x40))
        bb.put(byteArrayOf(0x44, 0x89.toByte(), 0x88.toByte())).putDouble(60008.0)
        assertEquals(60.008, MediaProbe.webmDuration(bb.array())!!, 0.001)
        assertNull(MediaProbe.webmDuration(mp4(1000, 25_000)))
    }

    @Test fun readsHlsLength() {
        val vod = "#EXTM3U\n#EXT-X-TARGETDURATION:6\n#EXTINF:6.0,\na.ts\n#EXTINF:6.0,\nb.ts\n#EXTINF:3.5,\nc.ts\n#EXT-X-ENDLIST\n"
        assertEquals(15.5, MediaProbe.hlsDuration(vod)!!, 0.001)
        assertEquals("live = long", Double.POSITIVE_INFINITY, MediaProbe.hlsDuration(vod.replace("#EXT-X-ENDLIST\n", ""))!!, 0.0)
        assertNull(MediaProbe.hlsDuration("<html>not a playlist</html>"))
    }

    @Test fun readsRealFfmpegFiles() {
        // Generated by the desktop test suite (npm test); skipped if it hasn't run here.
        val dir = java.io.File("../../test/fixtures/media2")
        org.junit.Assume.assumeTrue(dir.isDirectory)
        fun head(n: String) = java.io.File(dir, n).inputStream().use { it.readNBytes(65536) }
        assertEquals(25.0, MediaProbe.mp4Duration(head("short.mp4"))!!, 0.01)
        assertEquals(200.0, MediaProbe.mp4Duration(head("long.mp4"))!!, 0.01)
        assertNull(MediaProbe.mp4Duration(head("long-nofast.mp4")))
        assertEquals(60.0, MediaProbe.webmDuration(head("eruption.webm"))!!, 0.05)
        assertEquals(60.0, MediaProbe.hlsDuration(java.io.File(dir, "stream/index.m3u8").readText())!!, 0.01)
    }

    // ---- choosing, with a fake length reader

    private val lengths = mapOf("ad.mp4" to 25.0, "mid.mp4" to 60.0, "feature.mp4" to 200.0)
    private val prober: (Candidate) -> Double? = { c -> lengths[c.src.substringAfterLast('/')] }
    private fun pick(cands: List<Candidate>, metas: Map<String, String> = emptyMap()) =
        Inspector.finalize(Hit("https://news.example/story"), Probe("https://news.example/story", metas = metas), cands, prober)
    private fun net(name: String, seq: Int) = Candidate("file", "https://cdn.example/$name", "network", "https://news.example/story", seq = seq)

    @Test fun playerLoadsAdThenVideo_picksTheVideo() {
        val v = pick(listOf(net("ad.mp4", 1), net("feature.mp4", 2)))
        assertEquals("https://cdn.example/feature.mp4", v.single().src)
    }

    @Test fun onlyTheAdWasRequested_yieldsNothing() {
        assertTrue(pick(listOf(net("ad.mp4", 1))).isEmpty())
    }

    @Test fun videoInsideAnAdContainer_isSkipped() {
        val live = Probe("https://news.example/story", live = true, videos = listOf(
            ProbeVideo("https://cdn.example/feature.mp4", emptyList(), null, null, 640.0, 360.0, ad = true),
            ProbeVideo("https://cdn.example/other.mp4", emptyList(), null, 300.0, 640.0, 360.0),
        ))
        val v = Inspector.finalize(Hit("https://news.example/story"), live, Inspector.candidatesFromProbe(live), prober)
        assertEquals("https://cdn.example/other.mp4", v.single().src)
        assertEquals("live", v.single().via)
    }

    @Test fun pageDeclaresLongVideo_rejectsShorterClip() {
        val declared = Candidate("embed", "https://player.example/1", "jsonld", "", provider = "other", id = "1", duration = 300.0)
        // 60 s clip passes the 45 s rule but is far shorter than the declared 5 minutes.
        assertTrue(pick(listOf(net("mid.mp4", 1)), mapOf("og:video:duration" to "300")).isEmpty())
        assertEquals("https://cdn.example/feature.mp4", pick(listOf(net("mid.mp4", 1), net("feature.mp4", 2)), mapOf("og:video:duration" to "300")).single().src)
        assertTrue(declared.duration == 300.0)
    }

    @Test fun unknownLengthIsNotRejected_andDeclaredShortIsTrusted() {
        assertEquals("https://cdn.example/unknown.mp4", pick(listOf(net("unknown.mp4", 1))).single().src)
        // A site's own JSON-LD saying 30 s is trusted (20 s floor), unlike a sniffed 30 s clip.
        val ld = Candidate("file", "https://cdn.example/clip30.mp4", "jsonld", "", title = "Clip", duration = 30.0)
        assertEquals(1, pick(listOf(ld)).size)
        assertTrue(pick(listOf(net("clip30.mp4", 1).copy(duration = 30.0))).isEmpty())
    }

    @Test fun moreAdServersRecognised_withoutFalsePositives() {
        for (u in listOf("https://cdn.example.com/creative/abc.mp4", "https://x.com/v.mp4?ad_type=preroll", "https://cdn.site.com/video-ads/x.mp4", "https://pagead2.googleads.g.doubleclick.net/x"))
            assertTrue(u, isAdUrl(u))
        for (u in listOf("https://www.headlines.com/adventure/volcano.mp4", "https://cdn.loadvideo.com/road/lava.mp4", "https://downloads.example.org/admin/video.mp4", "https://cdn.site.com/videos/volcano.mp4"))
            assertTrue(u, !isAdUrl(u))
    }
}
